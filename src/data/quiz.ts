/**
 * Цены не дублируются: берутся из того же `content.ts`, что и витрина пакетов на
 * экране 3 (правило репо №1). Поменялась цена в pricing.md - правим один раз в
 * content.ts, и квиз меняется вместе с витриной.
 *
 * Если пакет переименуют, а здесь забудут - билд упадёт с внятной ошибкой.
 * Это лучше, чем молча собранный сайт с пустой ценой на экране результата.
 */
const priceOfPackage = (name: string): string => {
  const pkg = botPackages.find((item) => item.name === name);
  if (!pkg) {
    throw new Error(`quiz.ts: в content.ts нет пакета ${name} - цену для результата брать неоткуда`);
  }
  return pkg.price;
};

const priceOfProduct = (name: string): string => {
  const product = siteProducts.find((item) => item.name === name);
  if (!product) {
    throw new Error(`quiz.ts: в content.ts нет продукта «${name}» - цену для связки брать неоткуда`);
  }
  return product.price;
};

