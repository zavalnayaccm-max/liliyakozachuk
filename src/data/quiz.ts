/**
 * Порядок разбора ничьей - из quiz-spec.md:
 *  1. СБ наверху - рекомендуем связку: это флагман и выше по чеку.
 *  2. Ничья между ботами - рекомендуем более дорогой из равных (защита от
 *     занижения, `role.md`). «Ночной администратор» и «Игровой бот» стоят
 *     одинаково (от 25 000 ₽), поэтому между ними порядок задан явно: НА выше,
 *     потому что закрывает самую частую боль аватара - утекающие заявки.
 *     Спека этот подслучай не оговаривает - если Лилия решит иначе, меняется
 *     одна строка ниже.
 *  3. «Квиз-воронка» (от 15 000 ₽) - последняя в очереди как самая дешёвая.
 */
export const BUCKET_ORDER: BucketId[] = ['SB', 'NA', 'IB', 'KV'];

export type Scores = Record<BucketId, number>;

/**
 * Считает баллы по корзинам.
 * `answers[i]` - индекс выбранного варианта в вопросе `i`, либо null (не отвечен).
 * Мусорные значения (нет такого вопроса, нет такого варианта) просто не считаются:
 * подсчёт не должен падать из-за подправленного руками URL или старого состояния.
 */
export function scoreAnswers(answers: ReadonlyArray<number | null>): Scores {
  const totals: Scores = { NA: 0, KV: 0, IB: 0, SB: 0 };

  answers.forEach((choice, questionIndex) => {
    if (choice === null) return;
    const option = questions[questionIndex]?.options[choice];
    if (!option) return;
    for (const bucket of BUCKET_ORDER) {
      totals[bucket] += option.score[bucket] ?? 0;
    }
  });

  return totals;
}

/**
 * Рекомендация: корзина с максимумом баллов, ничьи - по BUCKET_ORDER.
 *
 * Если баллов нет вообще (пустые ответы - такого в интерфейсе не бывает, но
 * функция обязана возвращать что-то осмысленное), вернётся связка: это главный
 * оффер, и он же первый в порядке приоритета.
 */
export function recommend(answers: ReadonlyArray<number | null>): BucketId {
  const totals = scoreAnswers(answers);
  const max = Math.max(...BUCKET_ORDER.map((bucket) => totals[bucket]));
  return BUCKET_ORDER.find((bucket) => totals[bucket] === max) ?? 'SB';
}
